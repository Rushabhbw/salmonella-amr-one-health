#!/usr/bin/env python3
"""
00_log_data_provenance.py

Writes docs/data_provenance.md AUTOMATICALLY from:
  * the raw files in data/raw/*.tsv        (rows, columns, size, SHA-256 checksum, file date)
  * config/download_manifest.tsv           (the search query and the count NCBI showed in the browser)

Nothing has to be typed into the log by hand. To change the query text, expected count or
download date, edit config/download_manifest.tsv and run this script again.

Run from the repository root:
    python workflow/scripts/00_log_data_provenance.py

Exit code is 1 if a file is missing, a row count is off, or the files have different columns.
"""
import argparse
import hashlib
from datetime import datetime
from pathlib import Path

import pandas as pd

SOURCE = "NCBI Pathogen Detection, Isolates Browser (https://www.ncbi.nlm.nih.gov/pathogens/isolates/)"


def sha256_of(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def read_table(path):
    df = pd.read_csv(path, sep="\t", dtype=str)
    df.columns = [c.lstrip("#") for c in df.columns]
    return df


def file_facts(path, tolerance_pct, expected_rows):
    df = read_table(path)
    rows = len(df)
    p = Path(path)
    facts = {
        "rows": rows,
        "columns": list(df.columns),
        "size_mb": round(p.stat().st_size / 1_000_000, 2),
        "sha256": sha256_of(path),
        "file_date": datetime.fromtimestamp(p.stat().st_mtime).strftime("%Y-%m-%d %H:%M"),
    }
    if expected_rows is None:
        facts["diff"], facts["status"] = "", "NO EXPECTED COUNT"
    else:
        diff = rows - expected_rows
        facts["diff"] = f"{diff:+d}"
        limit = expected_rows * tolerance_pct / 100.0
        if diff == 0:
            facts["status"] = "OK (exact)"
        elif abs(diff) <= limit:
            facts["status"] = f"OK (within {tolerance_pct}%)"
        else:
            facts["status"] = "CHECK"
    return facts


def build_log(raw_dir, manifest_path, tolerance_pct):
    manifest = pd.read_csv(manifest_path, sep="\t", dtype=str).fillna("")
    problems, rows_out, all_cols, hashes = [], [], {}, []

    listed = set(manifest["file"])
    extra = sorted(p.name for p in Path(raw_dir).glob("*.tsv") if p.name not in listed)
    for name in extra:
        problems.append(f"{name} is in {raw_dir} but not in the manifest")

    for _, m in manifest.iterrows():
        path = Path(raw_dir) / m["file"]
        if not path.exists():
            problems.append(f"{m['file']} is listed in the manifest but missing from {raw_dir}")
            rows_out.append([m["file"], m["query"], "", "", m["expected_rows"], "", "MISSING", "", ""])
            continue
        exp = int(m["expected_rows"]) if m["expected_rows"].strip() else None
        f = file_facts(path, tolerance_pct, exp)
        if f["status"] == "CHECK":
            problems.append(f"{m['file']}: {f['rows']} rows, expected {exp} ({f['diff']})")
        all_cols[m["file"]] = f["columns"]
        date = m["download_date"].strip()
        date_txt = date if date else f"{f['file_date']} (file timestamp)"
        rows_out.append([m["file"], m["query"], date_txt, f["rows"], m["expected_rows"], f["diff"],
                         f["status"], f["size_mb"], f["sha256"][:12]])
        hashes.append((m["file"], f["sha256"]))

    # all files must share exactly the same columns
    col_sets = {tuple(c) for c in all_cols.values()}
    first_cols = list(next(iter(all_cols.values()))) if all_cols else []
    if len(col_sets) > 1:
        problems.append("The files do not all have the same columns. Re-download with the same columns ticked.")

    L = []
    L.append("# Data provenance log\n")
    L.append("> AUTO-GENERATED by `workflow/scripts/00_log_data_provenance.py`. Do not edit by hand. "
             "To change a query, expected count or download date, edit `config/download_manifest.tsv` and run the script again.\n")
    L.append(f"Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')}  \nSource: {SOURCE}  \n"
             "Download method: Download button, tab-delimited (TSV) table, all available columns ticked.  \n"
             "Raw files live in `data/raw/` and are not committed to Git (see `.gitignore`).\n")
    L.append("## Files\n")
    head = ["File", "Search query", "Download date", "Rows", "Expected rows", "Difference", "Status", "Size (MB)", "SHA-256 (first 12)"]
    L.append("| " + " | ".join(head) + " |")
    L.append("|" + "|".join(["---"] * len(head)) + "|")
    for r in rows_out:
        L.append("| " + " | ".join(str(x) for x in r) + " |")
    L.append("")
    L.append("Rows exclude the header line. 'Expected rows' is the count the Isolates Browser showed for the same query "
             f"on the expected date in the manifest; NCBI updates daily, so a difference up to {tolerance_pct}% is accepted.\n")
    L.append("## Problems found\n")
    L.append(("- " + "\n- ".join(problems) + "\n") if problems else "None.\n")
    L.append(f"## Columns ({len(first_cols)}), identical in every file: {'yes' if len(col_sets) <= 1 else 'NO'}\n")
    L.append("; ".join(f"{i}. {c}" for i, c in enumerate(first_cols, 1)) + "\n")
    L.append("## Full SHA-256 checksums\n")
    L.append("Use these to prove a file has not changed (PowerShell: `Get-FileHash data\\raw\\<file> -Algorithm SHA256`).\n")
    L.append("```\n" + "\n".join(f"{h}  {n}" for n, h in hashes) + "\n```\n")
    L.append("## Known limitations\n")
    L.append("- The download date shown as 'file timestamp' is the date the file was last saved on this computer, so it is approximate. "
             "Write the exact date in the `download_date` column of the manifest to replace it.\n"
             "- The search query text comes from the manifest; this script cannot check what was typed into the website.\n"
             "- Antibiotic results are submitter-supplied and not vetted by NCBI beyond basic quality control.\n")
    return "\n".join(L), problems


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--raw-dir", default="data/raw")
    ap.add_argument("--manifest", default="config/download_manifest.tsv")
    ap.add_argument("--out", default="docs/data_provenance.md")
    ap.add_argument("--tolerance-pct", type=float, default=1.0)
    a = ap.parse_args(argv)

    text, problems = build_log(a.raw_dir, a.manifest, a.tolerance_pct)
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(text, encoding="utf-8")
    print(f"Wrote {a.out}  |  problems: {len(problems)}")
    for p in problems:
        print("  PROBLEM:", p)
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
